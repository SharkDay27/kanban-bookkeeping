function generateExplorationDialogue(names,kind,ctx){
  if(!Array.isArray(names)||names.length<2)return [];
  const first=names[0],second=names[1];
  const lines=[
    {speaker:first,text:explorationEventLine(first,kind,ctx),visibility:'public'},
    {speaker:second,text:explorationPairReply(second,first,kind,ctx),visibility:'public'}
  ];

  if((first==='良秀'||second==='良秀')&&Math.random()<0.28){
    const ryoshuLine=lines.find(function(x){return x.speaker==='良秀'});
    lines.push({
      speaker:'阿賴耶識（刀鞘）',
      text:pick(['刀鞘轻轻震了一声。','刀鞘传来两下短促的轻响。','刀鞘在良秀手边轻轻碰了一下。']),
      visibility:'public',
      kind:'scabbard'
    });

    const abbreviated=ryoshuLine&&typeof isRyoshuAbbreviatedSpeech==='function'&&isRyoshuAbbreviatedSpeech(ryoshuLine.text);
    const araya=abbreviated
      ?pick([
          '妈妈是在说，她已经看出哪里不对了。',
          '妈妈的意思是，先别急着动手，她还在看。',
          '嗯……妈妈那句是在说，刚才的方法不够好。'
        ])
      :pick([
          ctx&&ctx.success?'我也看到了。刚才真正有效的是两个人配合上的那一段。':'我觉得先退没有关系。至少我们已经知道它会怎么反击。',
          '妈妈刚才不是只在嫌弃。她其实一直在看对方动作哪里不自然。',
          '她会说成那样，不过我觉得她已经记住这次的节奏了。'
        ]);
    lines.push({speaker:'阿賴耶（刀鞘內）',text:araya,visibility:'user-only',kind:'inner-voice'});
  }
  return lines;
}
