function interactiveSinnerLines(members,entry){
  if(!members||!members.length)return [];
  const lines=[{speaker:members[0].name,text:sinnerLine(members[0],entry),visibility:'public'}];
  for(let i=1;i<members.length;i++){
    const current=members[i],previous=members[i-1];
    lines.push({speaker:current.name,text:sinnerInteractiveReply(current,previous,entry),visibility:'public'});
  }
  return lines;
}
function appendSinnerAfterAraya(lines,sinner,entry){
  // 阿賴耶的「意思／內在聲音」只有使用者能理解。
  // 罪人若在阿賴耶識之後接話，只能對刀鞘的晃動、震動或聲響做出反應。
  if(!Array.isArray(lines))lines=[];
  const observed=[...lines].reverse().find(function(line){return line&&line.visibility!=='user-only'});
  if(observed&&observed.kind==='scabbard'){
    // 多數情況下罪人只把刀鞘反應當作背景，不特地解讀或評論。
    // 偶爾才簡短注意到它，避免每次都出現「看不懂／別解讀」之類的重複對話。
    const text=Math.random()<0.32?scabbardObservedReaction(sinner):sinnerLine(sinner,entry);
    lines.push({speaker:sinner.name,text:text,visibility:'public'});
    return lines;
  }
  const previous=observed&&SINNERS.find(function(s){return s.name===observed.speaker});
  lines.push({
    speaker:sinner.name,
    text:previous?sinnerInteractiveReply(sinner,previous,entry):sinnerLine(sinner,entry),
    visibility:'public'
  });
  return lines;
}

function generateSinnerComment(entry){
  const roll=Math.random();
  const contexts=detectSituations(entry).map(function(x){return x.id});
  const meta={createdAt:new Date().toISOString(),category:entry.category,amountTier:amountTier(entry),amount:entry.amount,contexts:contexts};
  if(roll<0.01){const order=[...SINNERS].sort(function(){return Math.random()-.5});return {...meta,kind:'all',lines:interactiveSinnerLines(order,entry)}};
  const first=SINNERS[Math.floor(Math.random()*SINNERS.length)];
  if(first.name==='良秀'&&Math.random()<0.82)return {...meta,kind:'araya',lines:ryoshuArayaInteraction(entry)};
  if(roll<0.08){
    let second=SINNERS[Math.floor(Math.random()*SINNERS.length)];
    while(second.name===first.name)second=SINNERS[Math.floor(Math.random()*SINNERS.length)];
    return {...meta,kind:'duo',lines:interactiveSinnerLines([first,second],entry)};
  }
  return {...meta,kind:'single',lines:[{speaker:first.name,text:sinnerLine(first,entry)}]};
}
function commentKindLabel(kind){
  if(kind==='all')return 'RARE / 全員評議';
  if(kind==='duo')return 'RARE / 雙人評議';
  if(kind==='araya')return 'SPECIAL / 良秀・阿賴耶';
  return 'SINGLE / 單人評議';
}
